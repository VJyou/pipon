// Export Groth16 artifacts for the Solana program (groth16-solana byte layout).
//   node scripts/export_solana.cjs vk                      -> programs/zk_gate/src/vk.rs
//   node scripts/export_solana.cjs proof <proof> <public> [out.json] -> programs/zk_gate/tests/fixtures/claim.json
//   node scripts/export_solana.cjs cahash <ca.der>...      -> caKeyHash (= PoseidonLarge(121,17) of the RSA modulus)
const fs = require("fs");
const path = require("path");
const crypto = require("crypto");

const root = path.join(__dirname, "..");
const prog = path.join(root, "..", "programs", "zk_gate");
// BN254 base field modulus (for negating proof A).
const P = 21888242871839275222246405745257275088696311157297823662689037894645226208583n;

const be32 = (x) => BigInt(x).toString(16).padStart(64, "0");
const g1 = (p) => be32(p[0]) + be32(p[1]);
const g1neg = (p) => be32(p[0]) + be32((P - BigInt(p[1])) % P);
// snarkjs G2 [[x.c0, x.c1], [y.c0, y.c1]] -> x.c1 | x.c0 | y.c1 | y.c0
const g2 = (p) => be32(p[0][1]) + be32(p[0][0]) + be32(p[1][1]) + be32(p[1][0]);
const rsBytes = (hex) => "[" + hex.match(/../g).map((b) => "0x" + b).join(", ") + "]";

function exportVk() {
  const vk = JSON.parse(fs.readFileSync(path.join(root, "build", "vkey.json")));
  const lines = [
    "// Generated by circuits/scripts/export_solana.cjs from circuits/build/vkey.json. Do not edit.",
    "use groth16_solana::groth16::Groth16Verifyingkey;",
    "",
    `pub const NR_PUBLIC_INPUTS: usize = ${vk.nPublic};`,
    "",
    "pub const VERIFYINGKEY: Groth16Verifyingkey = Groth16Verifyingkey {",
    `    nr_pubinputs: ${vk.IC.length},`,
    `    vk_alpha_g1: ${rsBytes(g1(vk.vk_alpha_1))},`,
    `    vk_beta_g2: ${rsBytes(g2(vk.vk_beta_2))},`,
    `    vk_gamme_g2: ${rsBytes(g2(vk.vk_gamma_2))},`,
    `    vk_delta_g2: ${rsBytes(g2(vk.vk_delta_2))},`,
    "    vk_ic: &[",
    ...vk.IC.map((p) => `        ${rsBytes(g1(p))},`),
    "    ],",
    "};",
    "",
  ];
  fs.writeFileSync(path.join(prog, "src", "vk.rs"), lines.join("\n"));
  console.log(`vk.rs written (nPublic=${vk.nPublic})`);
}

function exportProof(proofPath, publicPath, outPath) {
  const proof = JSON.parse(fs.readFileSync(proofPath));
  const pub = JSON.parse(fs.readFileSync(publicPath));
  const input = JSON.parse(fs.readFileSync(process.env.INPUT || path.join(root, "fixtures", "dummy", "input.json")));
  const out = {
    proof_a: g1neg(proof.pi_a),
    proof_b: g2(proof.pi_b),
    proof_c: g1(proof.pi_c),
    public_inputs: pub.map(be32),
    nonce: process.env.NONCE || "12345",
    current_date: input.currentDate,
    prefecture_code: input.prefectureCode,
  };
  const dst = outPath || path.join(prog, "tests", "fixtures", "claim.json");
  fs.mkdirSync(path.dirname(dst), { recursive: true });
  fs.writeFileSync(dst, JSON.stringify(out, null, 2));
  console.log(`${dst} written`);
}

async function caHash(files) {
  const { buildPoseidon } = require("circomlibjs");
  const poseidon = await buildPoseidon();
  for (const f of files) {
    const der = fs.readFileSync(f);
    const jwk = new crypto.X509Certificate(der).publicKey.export({ format: "jwk" });
    const n = BigInt("0x" + Buffer.from(jwk.n, "base64url").toString("hex"));
    const mask = (1n << 121n) - 1n;
    const c = Array.from({ length: 17 }, (_, i) => (n >> (121n * BigInt(i))) & mask);
    const merged = [];
    for (let i = 0; i < 9; i++) merged.push(i === 8 ? c[16] : c[2 * i] + (c[2 * i + 1] << 121n));
    const h = poseidon.F.toObject(poseidon(merged));
    console.log(`${path.basename(f)}  ${h}  0x${be32(h)}`);
  }
}

const [cmd, ...args] = process.argv.slice(2);
if (cmd === "vk") exportVk();
else if (cmd === "proof") exportProof(args[0], args[1], args[2]);
else if (cmd === "cahash") caHash(args);
else {
  console.error("usage: export_solana.cjs vk | proof <proof.json> <public.json> | cahash <ca.der>...");
  process.exit(1);
}
